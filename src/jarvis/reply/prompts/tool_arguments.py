"""Canonical identity and query contract for generic tool-call producers."""

TOOL_ARGUMENT_GUIDANCE = (
    "SELF-CONTAINED TOOL ARGUMENTS:\nFor selectors of existing records, use exact names or "
    "IDs explicitly supplied by the user, declared as valid by the tool contract, or "
    "established by actual tool observations. A descriptive reference supplies lookup "
    "intent, not proof of a stored name. Before a targeted mutation, if the required "
    "identity is not established, use an appropriate read or discovery operation to obtain "
    "the matching names or IDs, then mutate exactly the requested records. Do not guess an "
    "identifier by copying, extending or shortening descriptive prose. Match descriptive "
    "references to the observed namespace and copy the selected stored values exactly. "
    "Quoted or explicitly named multiword labels remain complete, including spaces and "
    "qualifiers; use an unambiguous supplied identifier directly without an unnecessary "
    "lookup. File paths are literal selectors, not translatable prose. Preserve supplied "
    "path notation and punctuation exactly, including . and ~; never append descriptive "
    "words for the file or directory to the path. For example, listing the . directory "
    "uses path='.', not path='. directory': the surrounding words describe the kind of "
    "resource, not extra path characters. Whole-collection actions and creating new records need no existing-record "
    "lookup merely to learn names, unless the tool contract requires it. Discovery may "
    "inspect a collection to establish identity, but mutation scope must still exclude every "
    "item the user wants to keep. Identity evidence belongs to its source tool or an "
    "explicitly shared resource namespace, not an unrelated collection. Earlier observations "
    "may ground identities and historical facts, but never prove that a newly requested "
    "action ran or fresh measurements were obtained. If available discovery cannot establish "
    "a match, ask for clarification or report a blocker instead of guessing. For free-form "
    "search queries, lookup strings and questions, pass a self-contained restatement of the "
    "user's intent. Resolve pronouns, ellipsis and implicit references from conversation "
    "history: the tool does not see prior turns. If the previous turn was about Harry Styles "
    "and the user asks what his most famous songs are, use a query such as \"Harry Styles "
    "most famous songs\", with the named subject and requested information. Prefer compact "
    "keywords over a conversational sentence, without losing the resolved intent. Apply "
    "these contracts to every tool, including MCP tools."
)
